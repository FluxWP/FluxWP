const fallback = g('circle.grid.2x2', 'apps', 'circle.grid.2x2.fill');

/** "more" tab → ellipsis; everything else follows the shared icon table. */
export function nativeGlyph(name?: string, slug?: string): Glyph {
  if (name === 'more' || name === 'menu') return g('ellipsis', 'more_horiz');
  return table.get(iconFor(name, slug)) ?? fallback;
}
