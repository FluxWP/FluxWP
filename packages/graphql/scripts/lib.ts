// Shared by generate.ts and the tests: reads plugin operations, builds persisted manifests and the
// generated TypeScript. Pure functions over strings; file I/O stays in generate.ts.
import { createHash } from 'node:crypto';
import {
  Kind,
  parse,
  print,
  validate,
  visit,
  type DocumentNode,
  type FragmentDefinitionNode,
  type GraphQLSchema,
  type OperationDefinitionNode,
} from 'graphql';

export interface SourceFile {
  /** Plugin slug (plugins/<slug>/graphql/operations/…). */
  plugin: string;
  path: string;
  body: string;
}

export interface Operation {
  plugin: string;
  name: string;
  kind: 'query' | 'mutation';
  document: string;
  id: string;
  path: string;
}

export class GenerateError extends Error {}

const NAME = /^Flx[A-Z][A-Za-z0-9]*$/;

/** Operations of every plugin, each with the fragments it uses (fragments are per plugin). */
export function collectOperations(schema: GraphQLSchema, files: SourceFile[]): Operation[] {
  const problems: string[] = [];
  type Entry = { ops: { node: OperationDefinitionNode; path: string }[]; frags: Map<string, FragmentDefinitionNode> };
  const byPlugin = new Map<string, Entry>();
  for (const f of files) {
    let doc: DocumentNode;
    try {
      doc = parse(f.body, { noLocation: false });
    } catch (e) {
      problems.push(`${f.path}: ${(e as Error).message}`);
      continue;
    }
    const entry: Entry = byPlugin.get(f.plugin) ?? { ops: [], frags: new Map() };
    byPlugin.set(f.plugin, entry);
    for (const def of doc.definitions) {
      if (def.kind === Kind.OPERATION_DEFINITION) {
        if (def.operation === 'subscription') problems.push(`${f.path}: subscriptions are not supported`);
        else entry.ops.push({ node: def, path: f.path });
      } else if (def.kind === Kind.FRAGMENT_DEFINITION) {
        if (entry.frags.has(def.name.value)) problems.push(`${f.path}: fragment ${def.name.value} is defined twice in ${f.plugin}`);
        entry.frags.set(def.name.value, def);
      } else {
        problems.push(`${f.path}: only operations and fragments belong in operation files`);
      }
    }
  }

  const seen = new Map<string, string>();
  const out: Operation[] = [];
  for (const [plugin, { ops, frags }] of byPlugin) {
    for (const { node, path } of ops) {
      const name = node.name?.value;
      if (!name) {
        problems.push(`${path}: every operation needs a name`);
        continue;
      }
      if (!NAME.test(name)) problems.push(`${path}: operation ${name} must be PascalCase and start with "Flx"`);
      const other = seen.get(name);
      if (other) problems.push(`${path}: operation ${name} is also defined in ${other}`);
      seen.set(name, path);

      const used = new Map<string, FragmentDefinitionNode>();
      const walk = (n: OperationDefinitionNode | FragmentDefinitionNode) =>
        visit(n, {
          FragmentSpread(s) {
            const name = s.name.value;
            if (used.has(name)) return;
            const frag = frags.get(name);
            if (!frag) {
              problems.push(`${path}: fragment ${name} is not defined in ${plugin}`);
              return;
            }
            used.set(name, frag);
            walk(frag);
          },
        });
      walk(node);
      const doc: DocumentNode = {
        kind: Kind.DOCUMENT,
        definitions: [node, ...[...used.values()].sort((a, b) => a.name.value.localeCompare(b.name.value))],
      };
      for (const err of validate(schema, doc)) problems.push(`${path}: ${err.message}`);
      const printed = print(stripLocations(doc));
      out.push({ plugin, name, kind: node.operation as 'query' | 'mutation', document: printed, id: sha256(printed), path });
    }
  }
  if (problems.length) throw new GenerateError(problems.join('\n'));
  return out.sort((a, b) => a.name.localeCompare(b.name));
}

function stripLocations(doc: DocumentNode): DocumentNode {
  return JSON.parse(JSON.stringify(doc, (k, v) => (k === 'loc' ? undefined : v))) as DocumentNode;
}

export const sha256 = (s: string) => createHash('sha256').update(s).digest('hex');

/** plugins/<slug>/graphql/persisted-queries.json contents, per plugin. */
export function manifests(ops: Operation[]): Map<string, string> {
  const by = new Map<string, Record<string, string>>();
  for (const op of ops) {
    const m = by.get(op.plugin) ?? {};
    m[op.id] = op.document;
    by.set(op.plugin, m);
  }
  const out = new Map<string, string>();
  for (const [plugin, m] of by) {
    const sorted = Object.fromEntries(Object.entries(m).sort(([a], [b]) => a.localeCompare(b)));
    out.set(plugin, JSON.stringify(sorted, null, 2) + '\n');
  }
  return out;
}

const HEADER = '// Generated by packages/graphql/scripts/generate.ts. Do not edit; run `bun run --filter @fluxwp/graphql generate`.\n';

/** Type name that typescript-operations gives an operation (dedupeOperationSuffix). */
export function typeNames(op: Pick<Operation, 'name' | 'kind'>): { result: string; variables: string } {
  const suffix = op.kind === 'query' ? 'Query' : 'Mutation';
  const base = op.name.endsWith(suffix) ? op.name : op.name + suffix;
  return { result: base, variables: base + 'Variables' };
}

export function operationsModule(ops: Operation[]): string {
  const lines = [HEADER, "import type { FlxOperation } from '../operation';"];
  if (ops.length) lines.push("import type * as T from './types';");
  lines.push('');
  for (const op of ops) {
    const t = typeNames(op);
    lines.push(
      `/** ${op.kind} ${op.name} (${op.plugin}, ${op.path}) */`,
      `export const ${op.name}: FlxOperation<T.${t.result}, T.${t.variables}> = {`,
      `  id: '${op.id}',`,
      `  name: '${op.name}',`,
      `  kind: '${op.kind}',`,
      `  plugin: '${op.plugin}',`,
      `  document: ${JSON.stringify(op.document)},`,
      '};',
      '',
    );
  }
  if (!ops.length) lines.push('export {};', '');
  return lines.join('\n');
}

export { HEADER };
