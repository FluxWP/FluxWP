// Schema snapshot in parts: one file per package, so parallel package pull requests never edit the same
// snapshot file (docs/graphql/KURALLAR.md §7).
//
//   packages/graphql/schema/core.graphql      WPGraphQL / WordPress types and anything without an owner
//   plugins/<slug>/graphql/schema.graphql     types and fields a plugin registers (`extend type` for
//   themes/<slug>/graphql/schema.graphql      fields it adds to types owned by someone else)
//
// The owner of each type and field comes from the kit (`wp flx-gql schema --owners`). Pure functions over
// strings; file I/O stays in the scripts.
import {
  buildASTSchema,
  concatAST,
  getNamedType,
  isInputObjectType,
  isInterfaceType,
  isObjectType,
  isUnionType,
  Kind,
  lexicographicSortSchema,
  parse,
  print,
  printSchema,
  type DefinitionNode,
  type DocumentNode,
  type FieldDefinitionNode,
  type GraphQLNamedType,
  type GraphQLSchema,
  type InputObjectTypeDefinitionNode,
  type InputValueDefinitionNode,
  type InterfaceTypeDefinitionNode,
  type ObjectTypeDefinitionNode,
  type TypeDefinitionNode,
  type TypeExtensionNode,
} from 'graphql';

/** Part of everything without an owner. */
export const CORE_PART = 'packages/graphql/schema/core.graphql';
/** The snapshot before it was split (read only when no part exists, e.g. on an old base commit). */
export const LEGACY_SNAPSHOT = 'packages/graphql/schema/schema.graphql';

/** { "FlxTask": "plugins/flx-tasks", "RootQuery.flxTasks": "plugins/flx-tasks", … } */
export type Owners = Record<string, string>;

export interface Part {
  /** Repository-relative path. */
  path: string;
  body: string;
}

const OWNER = /^(plugins|themes)\/[A-Za-z0-9_.-]+$/;

/** Repository-relative part file of an owner ('' = core). */
export function partPath(owner: string): string {
  if (owner === '') return CORE_PART;
  if (!OWNER.test(owner)) throw new Error(`invalid schema owner "${owner}"`);
  return `${owner}/graphql/schema.graphql`;
}

/** Owner of a part file ('' = core). */
export function partOwner(path: string): string {
  if (path === CORE_PART) return '';
  const m = /^((?:plugins|themes)\/[^/]+)\/graphql\/schema\.graphql$/.exec(path);
  if (!m) throw new Error(`not a schema part: ${path}`);
  return m[1]!;
}

const header = (owner: string) =>
  `# GraphQL schema snapshot: ${owner === '' ? 'WordPress / WPGraphQL core' : owner}.\n` +
  '# Generated by `bun run --filter @fluxwp/graphql schema`. Do not edit.\n\n';

type Field = FieldDefinitionNode | InputValueDefinitionNode;
type WithFields = ObjectTypeDefinitionNode | InterfaceTypeDefinitionNode | InputObjectTypeDefinitionNode;

function hasFields(d: TypeDefinitionNode): d is WithFields {
  return d.kind === Kind.OBJECT_TYPE_DEFINITION || d.kind === Kind.INTERFACE_TYPE_DEFINITION || d.kind === Kind.INPUT_OBJECT_TYPE_DEFINITION;
}

function isTypeDefinition(d: DefinitionNode): d is TypeDefinitionNode {
  return (
    d.kind === Kind.OBJECT_TYPE_DEFINITION ||
    d.kind === Kind.INTERFACE_TYPE_DEFINITION ||
    d.kind === Kind.INPUT_OBJECT_TYPE_DEFINITION ||
    d.kind === Kind.ENUM_TYPE_DEFINITION ||
    d.kind === Kind.UNION_TYPE_DEFINITION ||
    d.kind === Kind.SCALAR_TYPE_DEFINITION
  );
}

/** Splits a printed schema into parts by owner. Every owner that owns something gets a part; core always. */
export function splitSchema(sdl: string, owners: Owners): Part[] {
  // Normalised first (types, fields, values sorted), so the parts do not depend on registration order.
  const schema = lexicographicSortSchema(buildASTSchema(parse(sdl, { noLocation: true })));
  const doc = parse(printSchema(schema), { noLocation: true });
  for (const owner of new Set(Object.values(owners))) partPath(owner);

  // Field owner: explicit, else the interface field it implements (ContentNode.flxBlocks → Post.flxBlocks).
  const fieldOwner = (type: string, field: string): string | undefined => {
    const own = owners[`${type}.${field}`];
    if (own !== undefined) return own;
    const t = schema.getType(type);
    if (isObjectType(t) || isInterfaceType(t)) {
      for (const i of t.getInterfaces()) {
        const viaInterface = owners[`${i.name}.${field}`];
        if (viaInterface !== undefined) return viaInterface;
      }
    }
    return undefined;
  };

  // Type owner: explicit, else a "Flx…" type that only one owner's types and fields reach, else core.
  const typeOwner = new Map<string, string>();
  for (const name of Object.keys(schema.getTypeMap())) {
    if (name.startsWith('__')) continue;
    const own = owners[name];
    if (own !== undefined) typeOwner.set(name, own);
  }
  const reachedBy = new Map<string, Set<string>>();
  const refs = (t: GraphQLNamedType, context: string): GraphQLNamedType[] => {
    const out: GraphQLNamedType[] = [];
    if (isObjectType(t) || isInterfaceType(t)) {
      for (const f of Object.values(t.getFields())) {
        const o = fieldOwner(t.name, f.name);
        if (o !== undefined && o !== context) continue;
        out.push(getNamedType(f.type), ...f.args.map((a) => getNamedType(a.type)));
      }
      out.push(...t.getInterfaces());
    }
    if (isInterfaceType(t) || isUnionType(t)) out.push(...schema.getPossibleTypes(t));
    if (isInputObjectType(t)) for (const f of Object.values(t.getFields())) out.push(getNamedType(f.type));
    return out;
  };
  const walk = (start: GraphQLNamedType[], context: string) => {
    const queue = [...start];
    const seen = new Set<string>();
    while (queue.length) {
      const t = queue.pop()!;
      if (seen.has(t.name) || t.name.startsWith('__')) continue;
      seen.add(t.name);
      const own = typeOwner.get(t.name);
      if (own !== undefined && own !== context) continue;
      if (own === undefined) {
        const set = reachedBy.get(t.name) ?? new Set<string>();
        set.add(context);
        reachedBy.set(t.name, set);
      }
      queue.push(...refs(t, context));
    }
  };
  // Owner contexts start from the fields they add anywhere and from their own types.
  const contexts = new Map<string, GraphQLNamedType[]>();
  const add = (owner: string, t: GraphQLNamedType | null | undefined) => {
    if (!t) return;
    const list = contexts.get(owner) ?? [];
    list.push(t);
    contexts.set(owner, list);
  };
  for (const [coordinate, owner] of Object.entries(owners)) {
    const [typeName, fieldName] = coordinate.split('.');
    const t = schema.getType(typeName!);
    if (!fieldName) add(owner, t);
    else if (isObjectType(t) || isInterfaceType(t) || isInputObjectType(t)) {
      const f = t.getFields()[fieldName];
      if (f) {
        add(owner, getNamedType(f.type));
        if ('args' in f) for (const a of f.args) add(owner, getNamedType(a.type));
      }
    }
  }
  for (const [owner, start] of contexts) walk(start, owner);
  for (const [name, by] of reachedBy) {
    if (typeOwner.has(name) || !name.startsWith('Flx') || by.size !== 1) continue;
    typeOwner.set(name, [...by][0]!);
  }

  const defs = new Map<string, DefinitionNode[]>();
  const exts = new Map<string, Map<string, { def: WithFields; fields: Field[] }>>();
  const put = (owner: string, d: DefinitionNode) => {
    const list = defs.get(owner) ?? [];
    list.push(d);
    defs.set(owner, list);
  };
  for (const d of doc.definitions) {
    if (!isTypeDefinition(d)) {
      put('', d); // schema { … }, directives
      continue;
    }
    const owner = typeOwner.get(d.name.value) ?? '';
    if (!hasFields(d) || !d.fields) {
      put(owner, d);
      continue;
    }
    const mine: Field[] = [];
    for (const f of d.fields as readonly Field[]) {
      const o = fieldOwner(d.name.value, f.name.value) ?? owner;
      if (o === owner) {
        mine.push(f);
        continue;
      }
      const byType = exts.get(o) ?? new Map<string, { def: WithFields; fields: Field[] }>();
      exts.set(o, byType);
      const ext = byType.get(d.name.value) ?? { def: d, fields: [] };
      ext.fields.push(f);
      byType.set(d.name.value, ext);
    }
    put(owner, { ...d, fields: mine } as DefinitionNode);
  }

  const owner_list = new Set<string>(['', ...defs.keys(), ...exts.keys()]);
  const parts: Part[] = [];
  for (const owner of owner_list) {
    const own = [...(defs.get(owner) ?? [])].sort(byName);
    const ext = [...(exts.get(owner)?.values() ?? [])].map((e) => extensionOf(e.def, e.fields)).sort(byName);
    const body = print({ kind: Kind.DOCUMENT, definitions: [...own, ...ext] });
    parts.push({ path: partPath(owner), body: header(owner) + body + '\n' });
  }
  return parts.sort((a, b) => partOrder(a.path, b.path));
}

function extensionOf(d: WithFields, fields: Field[]): TypeExtensionNode {
  if (d.kind === Kind.OBJECT_TYPE_DEFINITION) return { kind: Kind.OBJECT_TYPE_EXTENSION, name: d.name, fields: fields as FieldDefinitionNode[] };
  if (d.kind === Kind.INTERFACE_TYPE_DEFINITION) return { kind: Kind.INTERFACE_TYPE_EXTENSION, name: d.name, fields: fields as FieldDefinitionNode[] };
  return { kind: Kind.INPUT_OBJECT_TYPE_EXTENSION, name: d.name, fields: fields as InputValueDefinitionNode[] };
}

function byName(a: DefinitionNode, b: DefinitionNode): number {
  const name = (d: DefinitionNode) => ('name' in d && d.name ? d.name.value : '');
  // schema { … } and directives first, then types by name.
  const rank = (d: DefinitionNode) => (d.kind === Kind.SCHEMA_DEFINITION ? 0 : d.kind === Kind.DIRECTIVE_DEFINITION ? 1 : 2);
  return rank(a) - rank(b) || (name(a) < name(b) ? -1 : name(a) > name(b) ? 1 : 0);
}

/** Core first, then the packages by path. */
export function partOrder(a: string, b: string): number {
  if (a === b) return 0;
  if (a === CORE_PART) return -1;
  if (b === CORE_PART) return 1;
  return a < b ? -1 : 1;
}

/** Builds the full schema from its parts (or from the legacy single snapshot). */
export function assembleSchema(parts: Part[]): GraphQLSchema {
  if (!parts.length) throw new Error('no schema parts found');
  const docs: DocumentNode[] = [...parts]
    .sort((a, b) => partOrder(a.path, b.path))
    .map((p) => {
      try {
        return parse(p.body, { noLocation: true });
      } catch (e) {
        throw new Error(`${p.path}: ${(e as Error).message}`);
      }
    });
  return lexicographicSortSchema(buildASTSchema(concatAST(docs)));
}

/** Printed full schema (sorted), for codegen, the breaking change check and diffs. */
export function assembleSdl(parts: Part[]): string {
  return printSchema(assembleSchema(parts)) + '\n';
}
