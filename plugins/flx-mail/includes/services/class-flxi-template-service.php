class FLXI_Template_Service {

	/**
	 * Seven-day send counts and the current sender line.
	 *
	 * @return array{sent:int,failed:int,blocked:int,senderName:string,senderEmail:string,method:string}
	 */
	public static function stats(): array {
		/** @var wpdb $wpdb */
		global $wpdb;
		$t     = flxi_table( 'log' );
		$since = gmdate( 'Y-m-d H:i:s', time() - 7 * DAY_IN_SECONDS );
		$sum   = array( 'sent' => 0, 'failed' => 0, 'blocked' => 0 );
		foreach ( flxi_rows( $wpdb->get_results( $wpdb->prepare( "SELECT status, COUNT(*) n FROM {$t} WHERE created_at >= %s GROUP BY status", $since ), ARRAY_A ) ) as $r ) { // phpcs:ignore WordPress.DB.PreparedSQL -- @phpstan-ignore argument.type
			$status = flxi_str( $r['status'] ?? '' );
			if ( isset( $sum[ $status ] ) ) {
				$sum[ $status ] = flxi_int( $r['n'] ?? 0 );
			}
		}
		$s      = flxi_arr( flxi_settings() );
		$method = flxi_other_smtp_plugin() ? flxi_str( flxi_other_smtp_plugin() ) : ( flxi_smtp_ready() ? 'SMTP · ' . flxi_str( $s['smtp_host'] ?? '' ) : __( 'PHP mail() (not recommended)', 'flx-mail' ) );
		if ( function_exists( 'flx_gql_cache_tag' ) ) {
			flx_gql_cache_tag( array( 'flx-mail:templates', 'flx-mail:log' ) );
		}
		return array(
			'sent'        => $sum['sent'],
			'failed'      => $sum['failed'],
			'blocked'     => $sum['blocked'],
			'senderName'  => flxi_str( $s['from_name'] ?? '' ),
			'senderEmail' => flxi_str( $s['from_email'] ?? '' ),
			'method'      => $method,
		);
	}

	/**
	 * Every template row the Emails screen lists.
	 *
	 * @return list<array<string,mixed>>
	 */
	public static function rows( string $search = '' ): array {
		$groups = array();
		foreach ( flxi_arr( flxi_email_types() ) as $k => $type ) {
			$type = flxi_arr( $type );
			$c    = flxi_arr( flxi_template( $k ) );
			$groups[ flxi_str( $type['group'] ?? '' ) ][] = self::row(
				flxi_str( $k ),
				flxi_str( $type['label'] ?? '' ),
				flxi_str( $type['description'] ?? '' ),
				'admin' === flxi_str( $type['recipient'] ?? '' ) ? __( 'To admin', 'flx-mail' ) : __( 'To user', 'flx-mail' ),
				(bool) ( $c['enabled'] ?? false ),
				flxi_str( $c['sender'] ?? '' ),
				(bool) ( $type['editable'] ?? false ),
				! ( $type['can_disable'] ?? false ),
				'registered',
				''
			);
		}
		foreach ( flxi_rows( flxi_wc_emails() ) as $e ) {
			$sender = flxi_str( flxi_arr( flxi_template( flxi_str( $e['key'] ?? '' ) ) )['sender'] ?? '' );
			$groups['WooCommerce'][] = self::row(
				flxi_str( $e['key'] ?? '' ),
				flxi_str( $e['label'] ?? '' ),
				flxi_str( $e['description'] ?? '' ),
				! empty( $e['customer'] ) ? __( 'To user', 'flx-mail' ) : __( 'To admin', 'flx-mail' ),
				(bool) ( $e['enabled'] ?? false ),
				'' !== $sender ? $sender : 'info',
				false,
				(bool) ( $e['manual'] ?? false ),
				'woocommerce',
				flxi_str( $e['edit_url'] ?? '' )
			);
		}
		foreach ( flxi_arr( flxi_discovered() ) as $k => $d ) {
			$d = flxi_arr( $d );
			$c = flxi_arr( flxi_template( $k ) );
			$groups[ __( 'Discovered', 'flx-mail' ) ][] = self::row(
				flxi_str( $k ),
				flxi_str( flxi_discovered_label( flxi_str( $k ), $d ) ),
				sprintf(
					/* translators: 1: count, 2: date */
					__( 'Sent %1$s times, last: %2$s. The content is generated by the plugin that sends it; here you can turn it on or off and choose the sender address and the branded layout.', 'flx-mail' ),
					number_format_i18n( flxi_int( $d['count'] ?? 0 ) ),
					flxi_str( flx_date( flxi_int( $d['last'] ?? 0 ) ) )
				),
				'',
				(bool) ( $c['enabled'] ?? false ),
				flxi_str( $c['sender'] ?? '' ) ? flxi_str( $c['sender'] ?? '' ) : flxi_str( flxi_default_sender( $k, flxi_str( $d['source'] ?? '' ) ) ),
				false,
				false,
				'discovered',
				''
			);
		}
		$order = array( 'WordPress' => 0, 'Flux Certificates' => 1, 'WooCommerce' => 2 );
		uksort(
			$groups,
			static function ( $a, $b ) use ( $order ) {
				return ( $order[ $a ] ?? 9 ) <=> ( $order[ $b ] ?? 9 ) ?: strcasecmp( flxi_str( $a ), flxi_str( $b ) );
			}
		);
		$needle = mb_strtolower( $search );
		$out    = array();
		foreach ( $groups as $group => $rows ) {
			foreach ( $rows as $row ) {
				$row['group'] = flxi_str( $group );
				if ( '' !== $needle ) {
					$hay = mb_strtolower( flxi_str( $row['label'] ?? '' ) . ' ' . flxi_str( $row['key'] ?? '' ) . ' ' . flxi_str( $row['group'] ) );
					if ( ! str_contains( $hay, $needle ) ) {
						continue;
					}
				}
				$out[] = $row;
			}
		}
		if ( function_exists( 'flx_gql_cache_tag' ) ) {
			flx_gql_cache_tag( 'flx-mail:templates' );
		}
		return $out;
	}

	/**
	 * @return array<string,mixed>
	 */
	private static function row( string $key, string $label, string $desc, string $to, bool $enabled, string $sender, bool $editable, bool $lock, string $kind, string $woo_url ): array {
		return array(
			'key'         => $key,
			'label'       => $label,
			'description' => $desc,
			'audience'    => $to,
			'enabled'     => $enabled,
			'sender'      => in_array( $sender, array( 'info', 'noreply' ), true ) ? $sender : 'info',
			'editable'    => $editable,
			'canDisable'  => ! $lock,
			'kind'        => $kind,
			'wooUrl'      => '' !== $woo_url ? $woo_url : null,
		);
	}

	/**
	 * Editor payload, or null when the key is unknown.
	 *
	 * @return array<string,mixed>|null
	 */
	public static function one( string $key ): ?array {
		$key   = sanitize_text_field( $key );
		$types = flxi_arr( flxi_email_types() );
		$type  = isset( $types[ $key ] ) ? flxi_arr( $types[ $key ] ) : array();
		$found = flxi_arr( flxi_discovered() );
		$disc  = isset( $found[ $key ] ) ? flxi_arr( $found[ $key ] ) : array();
		if ( ! $type && ! $disc && 0 !== strpos( $key, 'wc/' ) ) {
			return null;
		}
		$conf     = flxi_arr( flxi_template( $key ) );
		$defaults = flxi_arr( $type['defaults'] ?? array() );
		$editable = $type && ! empty( $type['editable'] );
		$sender   = flxi_str( $conf['sender'] ?? '' );
		if ( '' === $sender ) {
			$sender = $type ? flxi_str( $defaults['sender'] ?? 'info' ) : flxi_str( flxi_default_sender( $key, flxi_str( $disc['source'] ?? '' ) ) );
		}
		$vars = array();
		if ( $type && ! empty( $type['vars'] ) ) {
			$merged = array_merge(
				flxi_arr( $type['vars'] ),
				array(
					'site'          => __( 'Site name', 'flx-mail' ),
					'kurum'         => __( 'Organization name', 'flx-mail' ),
					'kurum_eposta'  => __( 'Organization email', 'flx-mail' ),
					'kurum_telefon' => __( 'Organization phone', 'flx-mail' ),
				)
			);
			foreach ( $merged as $name => $desc ) {
				$vars[] = array( 'name' => flxi_str( $name ), 'description' => flxi_str( $desc ) );
			}
		}
		$label = $type ? flxi_str( $type['label'] ?? '' ) : ( $disc ? flxi_discovered_label( $key, $disc ) : $key );
		if ( $type ) {
			$audience = 'admin' === flxi_str( $type['recipient'] ?? '' ) ? __( 'To admin', 'flx-mail' ) : __( 'To user', 'flx-mail' );
		} elseif ( $disc ) {
			$audience = '';
		} else {
			$wc = array();
			foreach ( flxi_rows( flxi_wc_emails() ) as $email ) {
				if ( flxi_str( $email['key'] ?? '' ) === $key ) {
					$wc = $email;
					break;
				}
			}
			$audience = ! empty( $wc['customer'] ) ? __( 'To user', 'flx-mail' ) : __( 'To admin', 'flx-mail' );
		}
		if ( function_exists( 'flx_gql_cache_tag' ) ) {
			flx_gql_cache_tag( 'flx-mail:templates' );
		}
		$woo = '';
		if ( ! $type && ! $disc ) {
			foreach ( flxi_rows( flxi_wc_emails() ) as $email ) {
				if ( flxi_str( $email['key'] ?? '' ) === $key ) {
					$woo = flxi_str( $email['edit_url'] ?? '' );
					break;
				}
			}
		}
		return array(
			'key'           => $key,
			'label'         => $label,
			'group'         => $type ? flxi_str( $type['group'] ?? '' ) : ( $disc ? __( 'Discovered', 'flx-mail' ) : 'WooCommerce' ),
			'audience'      => $audience,
			'description'   => $type ? flxi_str( $type['description'] ?? '' ) : ( $disc ? sprintf(
				/* translators: 1: source, 2: caller */
				__( 'Sender: %1$s (%2$s). The content is generated by that plugin.', 'flx-mail' ),
				flxi_str( flxi_source_label( flxi_str( $disc['source'] ?? '' ) ) ),
				flxi_str( $disc['caller'] ?? '' )
			) : '' ),
			'lastSubject'   => $disc ? flxi_str( $disc['subject'] ?? '' ) : '',
			'enabled'       => (bool) ( $conf['enabled'] ?? false ),
			'canDisable'    => ! $type || (bool) ( $type['can_disable'] ?? false ),
			'sender'        => in_array( $sender, array( 'info', 'noreply' ), true ) ? $sender : 'info',
			'senderInfo'    => flxi_str( flxi_setting( 'from_name' ) ) . ' <' . flxi_str( flxi_setting( 'from_email' ) ) . '>',
			'senderNoreply' => flxi_str( flxi_setting( 'noreply_name' ) ) . ' <' . flxi_str( flxi_setting( 'noreply_email' ) ) . '>',
			'editable'      => (bool) $editable,
			'kind'          => $type ? 'registered' : ( $disc ? 'discovered' : 'woocommerce' ),
			'subject'       => $editable ? flxi_str( $conf['subject'] ?? '' ) : '',
			'heading'       => $editable ? flxi_str( $conf['heading'] ?? '' ) : '',
			'body'          => $editable ? flxi_str( $conf['body'] ?? '' ) : '',
			'buttonText'    => $editable ? flxi_str( $conf['button_text'] ?? '' ) : '',
			'buttonUrl'     => $editable ? flxi_str( $conf['button_url'] ?? '' ) : '',
			'wrap'          => (bool) ( $conf['wrap'] ?? true ),
			'vars'          => $vars,
			'wooUrl'        => '' !== $woo ? $woo : null,
		);
	}

	/**
	 * Same rules as admin_post_flxi_toggle_template.
	 *
	 * @return true|WP_Error
	 */
	public static function toggle( string $key, bool $on ) {
		$key = sanitize_text_field( $key );
		if ( '' === $key ) {
			return new WP_Error( 'flxi_invalid', __( 'Choose an email.', 'flx-mail' ), array( 'status' => 400, 'field' => 'key' ) );
		}
		if ( 0 === strpos( $key, 'wc/' ) ) {
			flxi_wc_set_enabled( substr( $key, 3 ), $on );
		} else {
			$type = flxi_arr( flxi_arr( flxi_email_types() )[ $key ] ?? array() );
			if ( $type && empty( $type['can_disable'] ) ) {
				$on = true;
			}
			flxi_save_template( $key, array( 'enabled' => $on ) );
		}
		self::purge();
		return true;
	}

	/**
	 * Same rules as admin_post_flxi_save_template.
	 *
	 * @param array<string,mixed> $post Posted fields (key, reset, enabled, sender, subject, heading, body, button_text, button_url, wrap).
	 * @return true|WP_Error
	 */
	public static function save_post( array $post ) {
		$key  = sanitize_text_field( flxi_str( $post['key'] ?? '' ) );
		$type = flxi_arr( flxi_arr( flxi_email_types() )[ $key ] ?? array() );
		if ( '' === $key ) {
			return new WP_Error( 'flxi_invalid', __( 'Choose an email.', 'flx-mail' ), array( 'status' => 400, 'field' => 'key' ) );
		}
		if ( ! empty( $post['reset'] ) ) {
			flxi_reset_template( $key );
			self::purge();
			return true;
		}
		$data = array(
			'enabled' => ! empty( $post['enabled'] ) || ( $type && empty( $type['can_disable'] ) ),
			'sender'  => sanitize_key( flxi_str( $post['sender'] ?? '' ) ),
		);
		if ( $type && ! empty( $type['editable'] ) ) {
			$defaults = flxi_arr( $type['defaults'] ?? array() );
			foreach ( array( 'subject', 'heading', 'body', 'button_text', 'button_url' ) as $f ) {
				$v          = flxi_str( $post[ $f ] ?? '' );
				$data[ $f ] = trim( $v ) === trim( flxi_str( $defaults[ $f ] ?? '' ) ) ? '' : $v;
			}
		} else {
			$data['wrap'] = ! empty( $post['wrap'] );
		}
		if ( 0 === strpos( $key, 'wc/' ) ) {
			flxi_wc_set_enabled( substr( $key, 3 ), $data['enabled'] );
		}
		flxi_save_template( $key, $data );
		self::purge();
		return true;
	}

	/**
	 * @param array<string,mixed> $input GraphQL input.
	 * @return true|WP_Error
	 */
	public static function save_input( array $input ) {
		$post = array(
			'key'         => $input['key'] ?? '',
			'enabled'     => ! empty( $input['enabled'] ),
			'sender'      => strtolower( flxi_str( $input['sender'] ?? '' ) ),
			'subject'     => $input['subject'] ?? '',
			'heading'     => $input['heading'] ?? '',
			'body'        => $input['body'] ?? '',
			'button_text' => $input['buttonText'] ?? '',
			'button_url'  => $input['buttonUrl'] ?? '',
			'wrap'        => ! empty( $input['wrap'] ),
		);
		return self::save_post( $post );
	}

	/**
	 * @return true|WP_Error
	 */
	public static function reset( string $key ) {
		return self::save_post( array( 'key' => $key, 'reset' => 1 ) );
	}

	private static function purge(): void {
		if ( function_exists( 'flx_gql_purge' ) ) {
			flx_gql_purge( 'flx-mail:templates' );
		}
	}
}
