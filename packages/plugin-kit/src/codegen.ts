// Operations of a plugin outside the monorepo → typed operations + its persisted query manifest, against
// FluxWP's schema (@fluxwp/graphql schema/full.graphql) plus the plugin's own schema part.
//
//   <plugin>/graphql/schema.graphql          the plugin's types and fields (`flx-kit schema-split`), optional
//   <plugin>/graphql/operations/*.graphql    its operations, one per file, names Flx…
//   →  <plugin>/graphql/persisted-queries.json   register with the flx_gql_persisted_manifests filter (committed)
//   →  <out>/types.ts, <out>/operations.ts        import { FlxAcmeOrders } from './generated/operations'
//
// Same rules and output as the monorepo's packages/graphql/scripts/generate.ts (lib.ts is shared).
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative, resolve } from 'node:path';
import { buildSchema, parse } from 'graphql';
import { codegen as gqlCodegen } from '@graphql-codegen/core';
import * as typescriptOperations from '@graphql-codegen/typescript-operations';
import { collectOperations, manifests, operationsModule, type SourceFile } from '../../graphql/scripts/lib';
import { assembleSdl, CORE_PART } from '../../graphql/scripts/parts';

export interface CodegenOptions {
  /** Plugin folder (its slug is the folder name). */
  plugin: string;
  /** Folder for types.ts and operations.ts (default <plugin>/screens/generated). */
  out?: string;
  /** FluxWP schema (default: @fluxwp/graphql's schema/full.graphql). */
  schema?: string;
  /** Write nothing; return the manifest paths that are out of date. */
  check?: boolean;
}

export interface CodegenResult {
  operations: number;
  written: string[];
  stale: string[];
}

const HEADER = '// Generated by @fluxwp/plugin-kit (flx-kit codegen). Do not edit.\n';

function graphqlFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name);
    if (e.isDirectory()) return graphqlFiles(p);
    return e.isFile() && e.name.endsWith('.graphql') ? [p] : [];
  });
}

/** The FluxWP schema a plugin compiles against: an explicit file, else the one @fluxwp/graphql ships. */
export function defaultSchemaPath(from: string): string {
  for (let dir = resolve(from); ; dir = dirname(dir)) {
    const p = join(dir, 'node_modules/@fluxwp/graphql/schema/full.graphql');
    if (existsSync(p)) return p;
    if (dirname(dir) === dir) break;
  }
  throw new Error('FluxWP schema not found: install @fluxwp/graphql or pass --schema <file>.');
}

export async function codegen(o: CodegenOptions): Promise<CodegenResult> {
  const plugin = resolve(o.plugin);
  const slug = basename(plugin);
  const out = resolve(o.out ?? join(plugin, 'screens/generated'));
  const parts = [{ path: CORE_PART, body: readFileSync(o.schema ?? defaultSchemaPath(plugin), 'utf8') }];
  const own = join(plugin, 'graphql/schema.graphql');
  if (existsSync(own)) parts.push({ path: `plugins/${slug}/graphql/schema.graphql`, body: readFileSync(own, 'utf8') });
  const sdl = assembleSdl(parts);
  const sources: SourceFile[] = graphqlFiles(join(plugin, 'graphql/operations'))
    .sort()
    .map((path) => ({ plugin: slug, path: relative(plugin, path), body: readFileSync(path, 'utf8') }));
  const ops = collectOperations(buildSchema(sdl), sources);

  const types = await gqlCodegen({
    filename: 'types.ts',
    schema: parse(sdl),
    documents: ops.map((op) => ({ location: op.path, document: parse(op.document) })),
    plugins: [{ typescriptOperations: {} }],
    pluginMap: { typescriptOperations },
    config: {
      onlyOperationTypes: true,
      enumsAsTypes: true,
      useTypeImports: true,
      dedupeOperationSuffix: true,
      avoidOptionals: { field: true, inputValue: false, object: true, defaultValue: false },
      maybeValue: 'T | null',
      inputMaybeValue: 'T | null | undefined',
      strictScalars: true,
      scalars: { ID: 'string', FlxJSON: 'unknown' },
      defaultScalarType: 'unknown',
      skipTypename: false,
      nonOptionalTypename: false,
    },
  });
  const opsTs = operationsModule(ops)
    .replace(/^\/\/ Generated by .*\n/, HEADER)
    .replace("import type { FlxOperation } from '../operation';", "import type { FlxOperation } from '@fluxwp/graphql';");

  const files = new Map<string, string>([
    [join(out, 'types.ts'), HEADER + '/* eslint-disable */\n' + types],
    [join(out, 'operations.ts'), opsTs],
  ]);
  const manifest = manifests(ops).get(slug);
  const manifestPath = join(plugin, 'graphql/persisted-queries.json');
  const result: CodegenResult = { operations: ops.length, written: [], stale: [] };
  if (manifest) {
    const cur = existsSync(manifestPath) ? readFileSync(manifestPath, 'utf8') : null;
    if (cur !== manifest) {
      if (o.check) result.stale.push(manifestPath);
      else files.set(manifestPath, manifest);
    }
  } else if (existsSync(manifestPath)) {
    result.stale.push(manifestPath);
  }
  for (const [path, body] of files) {
    if (existsSync(path) && readFileSync(path, 'utf8') === body) continue;
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, body);
    result.written.push(path);
  }
  return result;
}
