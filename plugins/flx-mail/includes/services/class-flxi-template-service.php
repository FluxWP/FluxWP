class FLXI_Template_Service {

	/**
	 * Seven-day send counts and the current sender line.
	 *
	 * @return array{sent:int,failed:int,blocked:int,senderName:string,senderEmail:string,method:string}
	 */
	public static function stats(): array {
		global $wpdb;
		$t     = flxi_table( 'log' );
		$since = gmdate( 'Y-m-d H:i:s', time() - 7 * DAY_IN_SECONDS );
		$sum   = array( 'sent' => 0, 'failed' => 0, 'blocked' => 0 );
		foreach ( (array) $wpdb->get_results( $wpdb->prepare( "SELECT status, COUNT(*) n FROM {$t} WHERE created_at >= %s GROUP BY status", $since ), ARRAY_A ) as $r ) { // phpcs:ignore WordPress.DB.PreparedSQL
			if ( isset( $sum[ $r['status'] ] ) ) {
				$sum[ $r['status'] ] = (int) $r['n'];
			}
		}
		$s      = flxi_settings();
		$method = flxi_other_smtp_plugin() ? flxi_other_smtp_plugin() : ( flxi_smtp_ready() ? 'SMTP · ' . $s['smtp_host'] : __( 'PHP mail() (not recommended)', 'flx-mail' ) );
		if ( function_exists( 'flx_gql_cache_tag' ) ) {
			flx_gql_cache_tag( array( 'flx-mail:templates', 'flx-mail:log' ) );
		}
		return array(
			'sent'        => $sum['sent'],
			'failed'      => $sum['failed'],
			'blocked'     => $sum['blocked'],
			'senderName'  => (string) $s['from_name'],
			'senderEmail' => (string) $s['from_email'],
			'method'      => (string) $method,
		);
	}

	/**
	 * Every template row the Emails screen lists.
	 *
	 * @return list<array<string,mixed>>
	 */
	public static function rows( string $search = '' ): array {
		$groups = array();
		foreach ( flxi_email_types() as $k => $type ) {
			$c = flxi_template( $k );
			$groups[ $type['group'] ][] = self::row(
				(string) $k,
				(string) $type['label'],
				(string) $type['description'],
				'admin' === $type['recipient'] ? __( 'To admin', 'flx-mail' ) : __( 'To user', 'flx-mail' ),
				(bool) $c['enabled'],
				(string) $c['sender'],
				(bool) $type['editable'],
				! $type['can_disable'],
				'registered',
				''
			);
		}
		foreach ( flxi_wc_emails() as $e ) {
			$sender = flxi_template( $e['key'] )['sender'];
			$groups['WooCommerce'][] = self::row(
				(string) $e['key'],
				(string) $e['label'],
				(string) $e['description'],
				! empty( $e['customer'] ) ? __( 'To user', 'flx-mail' ) : __( 'To admin', 'flx-mail' ),
				(bool) $e['enabled'],
				$sender ? (string) $sender : 'info',
				false,
				(bool) $e['manual'],
				'woocommerce',
				(string) $e['edit_url']
			);
		}
		foreach ( flxi_discovered() as $k => $d ) {
			$c = flxi_template( $k );
			$groups[ __( 'Discovered', 'flx-mail' ) ][] = self::row(
				(string) $k,
				flxi_discovered_label( $k, $d ),
				sprintf(
					/* translators: 1: count, 2: date */
					__( 'Sent %1$s times, last: %2$s. The content is generated by the plugin that sends it; here you can turn it on or off and choose the sender address and the branded layout.', 'flx-mail' ),
					number_format_i18n( (int) $d['count'] ),
					flx_date( (int) $d['last'] )
				),
				'',
				(bool) $c['enabled'],
				$c['sender'] ? (string) $c['sender'] : flxi_default_sender( $k, (string) ( $d['source'] ?? '' ) ),
				false,
				false,
				'discovered',
				''
			);
		}
		$order = array( 'WordPress' => 0, 'Flux Certificates' => 1, 'WooCommerce' => 2 );
		uksort(
			$groups,
			static function ( $a, $b ) use ( $order ) {
				return ( $order[ $a ] ?? 9 ) <=> ( $order[ $b ] ?? 9 ) ?: strcasecmp( (string) $a, (string) $b );
			}
		);
		$needle = mb_strtolower( $search );
		$out    = array();
		foreach ( $groups as $group => $rows ) {
			foreach ( $rows as $row ) {
				$row['group'] = (string) $group;
				if ( '' !== $needle ) {
					$hay = mb_strtolower( $row['label'] . ' ' . $row['key'] . ' ' . $row['group'] );
					if ( ! str_contains( $hay, $needle ) ) {
						continue;
					}
				}
				$out[] = $row;
			}
		}
		if ( function_exists( 'flx_gql_cache_tag' ) ) {
			flx_gql_cache_tag( 'flx-mail:templates' );
		}
		return $out;
	}

	/**
	 * @return array<string,mixed>
	 */
	private static function row( string $key, string $label, string $desc, string $to, bool $enabled, string $sender, bool $editable, bool $lock, string $kind, string $woo_url ): array {
		return array(
			'key'         => $key,
			'label'       => $label,
			'description' => $desc,
			'audience'    => $to,
			'enabled'     => $enabled,
			'sender'      => in_array( $sender, array( 'info', 'noreply' ), true ) ? $sender : 'info',
			'editable'    => $editable,
			'canDisable'  => ! $lock,
			'kind'        => $kind,
			'wooUrl'      => '' !== $woo_url ? $woo_url : null,
		);
	}

	/**
	 * Editor payload, or null when the key is unknown.
	 *
	 * @return array<string,mixed>|null
	 */
	public static function one( string $key ): ?array {
		$key   = sanitize_text_field( $key );
		$types = flxi_email_types();
		$type  = $types[ $key ] ?? null;
		$disc  = flxi_discovered()[ $key ] ?? null;
		if ( ! $type && ! $disc && 0 !== strpos( $key, 'wc/' ) ) {
			return null;
		}
		$conf     = flxi_template( $key );
		$editable = $type && $type['editable'];
		$sender   = $conf['sender'] ? (string) $conf['sender'] : ( $type ? (string) $type['defaults']['sender'] : flxi_default_sender( $key, (string) ( $disc['source'] ?? '' ) ) );
		$vars     = array();
		if ( $type && ! empty( $type['vars'] ) ) {
			$merged = array_merge(
				(array) $type['vars'],
				array(
					'site'          => __( 'Site name', 'flx-mail' ),
					'kurum'         => __( 'Organization name', 'flx-mail' ),
					'kurum_eposta'  => __( 'Organization email', 'flx-mail' ),
					'kurum_telefon' => __( 'Organization phone', 'flx-mail' ),
				)
			);
			foreach ( $merged as $name => $desc ) {
				$vars[] = array( 'name' => (string) $name, 'description' => (string) $desc );
			}
		}
		$label = $type ? (string) $type['label'] : ( $disc ? flxi_discovered_label( $key, $disc ) : $key );
		if ( function_exists( 'flx_gql_cache_tag' ) ) {
			flx_gql_cache_tag( 'flx-mail:templates' );
		}
		return array(
			'key'         => $key,
			'label'       => $label,
			'group'       => $type ? (string) $type['group'] : ( $disc ? __( 'Discovered', 'flx-mail' ) : 'WooCommerce' ),
			'description' => $type ? (string) $type['description'] : ( $disc ? sprintf(
				/* translators: 1: source, 2: caller */
				__( 'Sender: %1$s (%2$s). The content is generated by that plugin.', 'flx-mail' ),
				flxi_source_label( (string) $disc['source'] ),
				(string) $disc['caller']
			) : '' ),
			'lastSubject' => $disc ? (string) ( $disc['subject'] ?? '' ) : '',
			'enabled'     => (bool) $conf['enabled'],
			'canDisable'  => ! $type || (bool) $type['can_disable'],
			'sender'      => in_array( $sender, array( 'info', 'noreply' ), true ) ? $sender : 'info',
			'senderInfo'  => flxi_setting( 'from_name' ) . ' <' . flxi_setting( 'from_email' ) . '>',
			'senderNoreply' => flxi_setting( 'noreply_name' ) . ' <' . flxi_setting( 'noreply_email' ) . '>',
			'editable'    => (bool) $editable,
			'kind'        => $type ? 'registered' : ( $disc ? 'discovered' : 'woocommerce' ),
			'subject'     => $editable ? (string) ( $conf['subject'] ?? '' ) : '',
			'heading'     => $editable ? (string) ( $conf['heading'] ?? '' ) : '',
			'body'        => $editable ? (string) ( $conf['body'] ?? '' ) : '',
			'buttonText'  => $editable ? (string) ( $conf['button_text'] ?? '' ) : '',
			'buttonUrl'   => $editable ? (string) ( $conf['button_url'] ?? '' ) : '',
			'wrap'        => (bool) ( $conf['wrap'] ?? true ),
			'vars'        => $vars,
			'wooUrl'      => ( ! $type && ! $disc && isset( flxi_wc_emails()[ substr( $key, 3 ) ] ) ) ? (string) flxi_wc_emails()[ substr( $key, 3 ) ]['edit_url'] : null,
		);
	}

	/**
	 * Same rules as admin_post_flxi_toggle_template.
	 *
	 * @return true|WP_Error
	 */
	public static function toggle( string $key, bool $on ) {
		$key = sanitize_text_field( $key );
		if ( '' === $key ) {
			return new WP_Error( 'flxi_invalid', __( 'Choose an email.', 'flx-mail' ), array( 'status' => 400, 'field' => 'key' ) );
		}
		if ( 0 === strpos( $key, 'wc/' ) ) {
			flxi_wc_set_enabled( substr( $key, 3 ), $on );
		} else {
			$type = flxi_email_types()[ $key ] ?? null;
			if ( $type && ! $type['can_disable'] ) {
				$on = true;
			}
			flxi_save_template( $key, array( 'enabled' => $on ) );
		}
		self::purge();
		return true;
	}

	/**
	 * Same rules as admin_post_flxi_save_template.
	 *
	 * @param array<string,mixed> $post Posted fields (key, reset, enabled, sender, subject, heading, body, button_text, button_url, wrap).
	 * @return true|WP_Error
	 */
	public static function save_post( array $post ) {
		$key  = sanitize_text_field( (string) ( $post['key'] ?? '' ) );
		$type = flxi_email_types()[ $key ] ?? null;
		if ( '' === $key ) {
			return new WP_Error( 'flxi_invalid', __( 'Choose an email.', 'flx-mail' ), array( 'status' => 400, 'field' => 'key' ) );
		}
		if ( ! empty( $post['reset'] ) ) {
			flxi_reset_template( $key );
			self::purge();
			return true;
		}
		$data = array(
			'enabled' => ! empty( $post['enabled'] ) || ( $type && ! $type['can_disable'] ),
			'sender'  => sanitize_key( (string) ( $post['sender'] ?? '' ) ),
		);
		if ( $type && $type['editable'] ) {
			foreach ( array( 'subject', 'heading', 'body', 'button_text', 'button_url' ) as $f ) {
				$v = (string) ( $post[ $f ] ?? '' );
				$data[ $f ] = trim( $v ) === trim( (string) $type['defaults'][ $f ] ) ? '' : $v;
			}
		} else {
			$data['wrap'] = ! empty( $post['wrap'] );
		}
		if ( 0 === strpos( $key, 'wc/' ) ) {
			flxi_wc_set_enabled( substr( $key, 3 ), $data['enabled'] );
		}
		flxi_save_template( $key, $data );
		self::purge();
		return true;
	}

	/**
	 * @param array<string,mixed> $input GraphQL input.
	 * @return true|WP_Error
	 */
	public static function save_input( array $input ) {
		$post = array(
			'key'         => $input['key'] ?? '',
			'enabled'     => ! empty( $input['enabled'] ),
			'sender'      => strtolower( (string) ( $input['sender'] ?? '' ) ),
			'subject'     => $input['subject'] ?? '',
			'heading'     => $input['heading'] ?? '',
			'body'        => $input['body'] ?? '',
			'button_text' => $input['buttonText'] ?? '',
			'button_url'  => $input['buttonUrl'] ?? '',
			'wrap'        => ! empty( $input['wrap'] ),
		);
		return self::save_post( $post );
	}

	public static function reset( string $key ) {
		return self::save_post( array( 'key' => $key, 'reset' => 1 ) );
	}

	private static function purge(): void {
		if ( function_exists( 'flx_gql_purge' ) ) {
			flx_gql_purge( 'flx-mail:templates' );
		}
	}
}
